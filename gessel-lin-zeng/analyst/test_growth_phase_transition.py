"""
Test TWO more GLZ-specific questions before the go/pivot checkpoint:
1. Does the combined 1-step GLZ map G_j on equal-degree quads (E_{k,i}) break
   even when restricted to GLZ-like parameters (deg d = 2j-3, balanced scales,
   and J in [1+4/j, 2.7]), OR was the earlier j=80 Nelder-Mead break purely
   from degenerate tiny-degree/unbalanced inputs?
2. Test the FULL GLZ addition step F_i = D_m h_i + h_{i-1} on Two-Regime inputs
   (4-tuples h_0, h_1, h_2, h_3 with J_raw >= 1 on (-1, -1/m], A > 0, and
   A'(0) < 0 where J_raw(0) < 1): does F_i preserve J_raw >= 1 on (-1, -1/(m+1)]
   and Plain Turan?
"""
import numpy as np
import mpmath as mp

mp.mp.dps = 100

def apply_Dm_mp(m, c):
    out = [mp.mpf(0)] * (len(c) + 1)
    for j, cj in enumerate(c):
        out[j] += (j + 1) * cj
        out[j + 1] += (j + m) * cj
    return out

def poly_add_mp(a, b):
    n = max(len(a), len(b))
    return [(a[j] if j < len(a) else mp.mpf(0)) + (b[j] if j < len(b) else mp.mpf(0)) for j in range(n)]

def eval_mp(c, t):
    v = d = mp.mpf(0)
    for coeff in reversed(c):
        d = d*t + v
        v = v*t + coeff
    return v, d

# PART 1: Test full GLZ step on d=1,2,3 4-tuples h0, h1, h2, h3 for Two-Regime closure!
# Take a 4-tuple generated by K steps of D_2 (or GLZ itself!) and perturb or apply D_m!
# Wait: EVEN BETTER — test our EXACT single-op / double-op counterexample mechanism:
# What happens to J_raw on (-1, -1/m] when we apply D_m(D_m h_i + h_{i-1}) with SLOWLY growing m = j+1
# vs CONSTANT m = 2 vs JUMPING m?!
def run_sequence(b_seq, name):
    # Start from k=1: htilde_{1,0} = D_{b_1}(1), htilde_{1,1} = 1
    ht = {(1, 0): apply_Dm_mp(b_seq[0], [mp.mpf(1)]), (1, 1): [mp.mpf(1)]}
    K = len(b_seq)
    for k in range(2, K + 1):
        bk = b_seq[k - 1]
        for i in range(k + 1):
            t1 = apply_Dm_mp(bk, ht[(k - 1, i)]) if i <= k - 1 else [mp.mpf(0)]
            t2 = ht[(k - 1, i - 1)] if i >= 1 else [mp.mpf(0)]
            ht[(k, i)] = apply_Dm_mp(bk, poly_add_mp(t1, t2))
    # Check min J_raw on (-1, -1/b_K] and min plain Turan on (-1, 0) at k = K!
    m = b_seq[-1] + 1
    t_split = mp.mpf(-1) / mp.mpf(m)
    grid_I = [-1 + (t_split + 1) * mp.mpf(j) / 40 for j in range(1, 41)]
    grid_II = [t_split * mp.mpf(30 - j) / 30 for j in range(30)] + [-mp.mpf(10)**(-p) for p in [4, 8, 12]] + [mp.mpf(0)]
    min_J_I = mp.inf
    min_J_II = mp.inf
    min_A = mp.inf
    bad_B = 0
    for i in range(1, K):
        g, f, h = ht[(K, i-1)], ht[(K, i)], ht[(K, i+1)]
        for tv in grid_I:
            gv, gd = eval_mp(g, tv); fv, fd = eval_mp(f, tv); hv, hd = eval_mp(h, tv)
            Wgf = gv*fd - gd*fv; Wfh = fv*hd - fd*hv; Wgh = gv*hd - gd*hv
            J = 4*Wgf*Wfh / (Wgh*Wgh) if Wgh != 0 else mp.inf
            if J < min_J_I: min_J_I = J
            A = (fv*fv - gv*hv) / (fv*fv + abs(gv*hv) + mp.mpf('1e-300'))
            if A < min_A: min_A = A
        for tv in grid_II:
            gv, gd = eval_mp(g, tv); fv, fd = eval_mp(f, tv); hv, hd = eval_mp(h, tv)
            Wgf = gv*fd - gd*fv; Wfh = fv*hd - fd*hv; Wgh = gv*hd - gd*hv
            J = 4*Wgf*Wfh / (Wgh*Wgh) if Wgh != 0 else mp.inf
            if J < min_J_II: min_J_II = J
            A = (fv*fv - gv*hv) / (fv*fv + abs(gv*hv) + mp.mpf('1e-300'))
            if A < min_A: min_A = A
            B = tv*(1+tv)*(2*fv*fd - gd*hv - gv*hd)
            if J < 1 and B < 0: bad_B += 1
    print(f"{name:28s} (K={K:2d}, b_K={b_seq[-1]:4d}): minA={float(min_A):.4e}, RegI minJ={float(min_J_I):.5f}, RegII minJ={float(min_J_II):.5f}, J<1&B<0={bad_B}")

print("=== PART 1: Growth-rate phase transition for b_j sequences! ===")
# Compare different growth rates of b_j!
run_sequence([j+1 for j in range(1, 26)], "GLZ linear b_j = j+1")
run_sequence([2]*25, "Constant b_j = 2")
run_sequence([j*j + 1 for j in range(1, 21)], "Quadratic b_j = j^2+1")
run_sequence([2**j for j in range(1, 16)], "Exponential b_j = 2^j")
run_sequence([3**j for j in range(1, 13)], "Fast exp b_j = 3^j")
run_sequence([5**j for j in range(1, 11)], "Very fast b_j = 5^j")
run_sequence([10**j for j in range(1, 9)], "Ultra fast b_j = 10^j")
run_sequence([2]*15 + [100, 100], "Step jump 2->100")
run_sequence([2]*15 + [1000, 1000], "Step jump 2->1000")
run_sequence([2]*15 + [10000, 10000], "Step jump 2->10000")
